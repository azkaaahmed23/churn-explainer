"""Step 2: load the cleaned data into SQLite, then run the profiling queries in sql/01_churn_profiling.sql.

Reads  data/processed/telco_clean.csv
Writes data/telco.db (table: customers) and docs/sql_profiling_results.md
"""
import re
import sqlite3
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
CSV = ROOT / "data" / "processed" / "telco_clean.csv"
DB = ROOT / "data" / "telco.db"
SQL_FILE = ROOT / "sql" / "01_churn_profiling.sql"
OUT = ROOT / "docs" / "sql_profiling_results.md"


def main() -> None:
    if not CSV.exists():
        raise SystemExit("Run `python src/clean.py` first.")

    # 1. Put the cleaned table into a SQLite database
    customers = pd.read_csv(CSV)
    con = sqlite3.connect(DB)
    customers.to_sql("customers", con, if_exists="replace", index=False)
    print(f"Loaded {len(customers):,} rows into {DB.relative_to(ROOT)} (table: customers)")

    # 2. The SQL file holds many queries, each starting with a line like "-- name: 02_churn_by_contract"
    text = SQL_FILE.read_text(encoding="utf-8")
    parts = re.split(r"^-- name:\s*(\S+)\s*$", text, flags=re.MULTILINE)
    queries = [(parts[i], parts[i + 1].strip()) for i in range(1, len(parts), 2)]

    # 3. Run each query, print the result, and save everything to one markdown file
    lines = ["# SQL profiling results", "", "_Generated by `src/sql_profile.py`. Do not edit by hand._", ""]
    for name, sql in queries:
        result = pd.read_sql_query(sql, con)
        print(f"\n=== {name} ===")
        print(result.to_string(index=False))
        lines += [f"## {name}", "", "```", result.to_string(index=False), "```", ""]
    con.close()

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"\nSaved -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
